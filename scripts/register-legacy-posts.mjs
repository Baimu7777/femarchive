// Regenerates publishing/existing-posts.mjs: the reviewed list of articles and
// news items written by hand before the forum could publish, so a forum post
// marked 已搬贴 can be connected to its archive copy and updated in place.
//
//   node scripts/register-legacy-posts.mjs          rewrite the registry
//   node scripts/register-legacy-posts.mjs --check  fail if it is out of date
//
// Each entry pins the committed Git blob of its file (`git ls-tree HEAD`, never
// the working copy, so line endings cannot differ from what GitHub holds). The
// receiver refuses the first adoption of a file edited after registration;
// run this again after such an edit and commit the result.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const root = fileURLToPath(new URL('..', import.meta.url));
const target = fileURLToPath(new URL('../publishing/existing-posts.mjs', import.meta.url));
// Identifiers already handed out stay what they were.
const pinned = { 'content/posts/35字词整理.md': '1ac5d0b7-46a2-407b-915b-cf9939f9211c' };

const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
const uuidFrom = seed => {
  const bytes = createHash('sha256').update(seed).digest().subarray(0, 16);
  bytes[6] = (bytes[6] & 0x0f) | 0x40; bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = bytes.toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
};

export function legacyEntries() {
  const entries = {};
  const listing = git(['-c', 'core.quotepath=off', 'ls-tree', 'HEAD', 'content/posts/', 'content/news/']).trim().split('\n');
  for (const line of listing) {
    const match = /^100644 blob ([0-9a-f]{40})\t(content\/(posts|news)\/([^/]+\.md))$/.exec(line);
    if (!match) continue;
    const [, revision, path, section, name] = match;
    // Files the receiver wrote are named by their identifier and already
    // managed by it; only hand-written ones are registered here.
    if (name === '_index.md' || /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.md$/.test(name)) continue;
    const source = git(['cat-file', 'blob', revision]);
    const front = /^(?:﻿)?---\r?\n([\s\S]*?)\r?\n---/.exec(source);
    if (!front) continue;
    const metadata = yaml.load(front[1]);
    // Only the hand-numbered files: anything the receiver wrote is already
    // managed by it, under its own identifier.
    const slug = typeof metadata?.slug === 'string' ? metadata.slug : '';
    if (!/^\d{6,}$/.test(slug) || typeof metadata.title !== 'string') continue;
    const id = pinned[path] ?? uuidFrom(`femarchive:legacy:${section}:${slug}`);
    entries[id] = { path, revision, title: metadata.title.replace(/[\r\n]+/g, ' ').slice(0, 200), section, slug };
  }
  return Object.fromEntries(Object.entries(entries).sort(([, a], [, b]) => a.path.localeCompare(b.path)));
}

export function registrySource(entries) {
  return `// Generated by scripts/register-legacy-posts.mjs from the committed Git blobs.
// Explicit administrator-reviewed legacy files. This never grants arbitrary
// browser-supplied paths; the first read must match the reviewed Git blob.
export const existingPosts = ${JSON.stringify(entries, null, 2)};

export const validExistingPostPath = value => typeof value === 'string'
  && /^content\\/(?:posts|news)\\/[^/\\\\\\u0000-\\u001f\\u007f?#%]{1,150}\\.md$/u.test(value)
  && !value.includes('..');
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = registrySource(legacyEntries());
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== next) {
      console.error('publishing/existing-posts.mjs is out of date: run node scripts/register-legacy-posts.mjs and commit it.');
      process.exit(1);
    }
  } else {
    writeFileSync(target, next);
    console.log(`Registered ${Object.keys(legacyEntries()).length} legacy articles and news items.`);
  }
}
